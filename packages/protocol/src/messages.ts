// Everything here goes over the socket rather than PostgREST, unlike the
// leaderboard: win rates are computed from game_players, which RLS keeps private
// on purpose (Security-Pass-2026-07-11), and a public view over it would have to
// grant anon read on every seat result of every game. The server aggregates
// instead and publishes only what the author asked to be public.

/** A player as the roster and their public profile show them. */
export const PlayerCardSchema = z.object({
  userId: z.string().uuid(),
  nickname: z.string(),
  avatar: z.string().nullable(),
  /** Ranked record only — that is the rate the author wants in the list. */
  ranked: CategoryRecordSchema,
  /** Best rating across the rated modes; null until a rated game is finished. */
  rating: z.number().nullable()
})
export type PlayerCard = z.infer<typeof PlayerCardSchema>

export const PlayersMessageSchema = z.object({
  t: z.literal('players'),
  seq,
  p: z.object({
    rows: z.array(PlayerCardSchema),
    /** Roster size under the same search, so the page control knows the end. */
    total: z.number().int().min(0)
  })
})

export const PlayerMessageSchema = z.object({
  t: z.literal('player'),
  seq,
  p: z.object({
    card: PlayerCardSchema,
    /** The same per-category record the player sees on their own profile. */
    record: ModeRecordSchema,
    ratings: z.array(
      z.object({
        mode: RankedModeSchema,
        rating: z.number(),
        games: z.number().int().min(0)
      })
    ),
    /**
     * Their achievements. The author asked for the public profile to show what a
     * player has done (backlog #2), and badges are exactly that; nothing here is
     * private — a badge is a fact about finished games. Optional for the same
     * reason as on `history`.
     */
    achievements: AchievementStateSchema.optional()
  })
})

