// --- Helpers -------------------------------------------------------------------------

export type ParsedClientMessage = { ok: true; msg: ClientMessage } | { ok: false; error: string }

/** Parse one inbound frame (JSON text or a pre-parsed value). Never throws. */
export function parseClientMessage(raw: unknown): ParsedClientMessage {
  let value = raw
  if (typeof raw === 'string') {
    try {
      value = JSON.parse(raw)
    } catch {
      return { ok: false, error: 'invalid JSON' }
    }
  }
  const result = ClientMessageSchema.safeParse(value)
  if (result.success) return { ok: true, msg: result.data }
  return { ok: false, error: z.prettifyError(result.error).slice(0, 300) }
}

export function encodeServerMessage(msg: ServerMessage): string {
  return JSON.stringify(msg)
}

