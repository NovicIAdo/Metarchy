/**
 * Live pre-commit staging shared with the 2v2 ally — structured table talk,
 * like chat.team. Display-only: never validated against game rules and never
 * part of game state. `turn` guards against stale ghosts after a phase flip.
 */
export const TeamStagingSchema = z.discriminatedUnion('kind', [
  z.strictObject({
    kind: z.literal('p2'),
    turn: z.number().int().min(1).max(9999),
    /** Staged (uncommitted) placements — a partial set while the ally decides. */
    placements: z
      .array(
        z.strictObject({
          actorType: ActorTypeSchema,
          locationId: LocationIdSchema,
          argument: ArgumentTypeSchema,
          bet: BetTypeSchema.optional()
        })
      )
      .max(4)
  }),
  z.strictObject({
    kind: z.literal('discard'),
    turn: z.number().int().min(1).max(9999),
    /** How much the ally is about to discard (P1 discard event, pre-commit). */
    amount: z.number().int().min(0).max(99)
  }),
  /** Retract everything staged (sent by the server on ally disconnect too). */
  z.strictObject({ kind: z.literal('clear'), turn: z.number().int().min(1).max(9999) })
])
export type TeamStaging = z.infer<typeof TeamStagingSchema>

