/**
 * One row of a player's record: games that produced a verdict for their seat,
 * and how they split. `wins` = game_players.result 'win'; `losses` = 'lose'
 * PLUS 'eliminated' — a forfeit or a dropped connection records as 'eliminated',
 * and the player did not win, so for a win rate it is a loss. Hence
 * played = wins + losses, always. Games that never produced a verdict (status
 * 'aborted' — a lobby that died, result null/'aborted') are in no row at all:
 * they were never played.
 */
export const CategoryRecordSchema = z.object({
  played: z.number().int().min(0),
  wins: z.number().int().min(0),
  losses: z.number().int().min(0)
})
export type CategoryRecord = z.infer<typeof CategoryRecordSchema>

/**
 * A player's whole archive split into disjoint categories (the server decides
 * which bucket a game lands in — `recordCategoryOf` in apps/server/src/store.ts):
 *  - `ranked`  public 1v1/ffa3 — the rated modes (server ratings.ts RATED_MODES);
 *  - `team`    public 2v2 — a real multiplayer mode, but unrated (team ratings
 *              are their own design), so it gets its own row instead of
 *              inflating the ranked win rate. Only public matchmaking can make
 *              one, and 2v2 is invite-only today, so this row is normally empty
 *              and the profile hides it rather than show a permanent 0;
 *  - `private` any invite game (games.is_private), whatever its mode;
 *  - `bots`    mode vs_bots — you played a machine.
 * `tutorial` is in none of them: it is a lesson, and every tutorial ends in a
 * forfeit, so counting it would hand every new player a loss.
 */
export const ModeRecordSchema = z.object({
  ranked: CategoryRecordSchema,
  team: CategoryRecordSchema,
  private: CategoryRecordSchema,
  bots: CategoryRecordSchema
})
export type ModeRecord = z.infer<typeof ModeRecordSchema>

/** Display order of the record table. */
export const RECORD_CATEGORIES = ['ranked', 'team', 'private', 'bots'] as const
export type RecordCategory = (typeof RECORD_CATEGORIES)[number]

/** A fresh all-zero record — the honest answer for a player who never finished a game. */
export function emptyModeRecord(): ModeRecord {
  return {
    ranked: { played: 0, wins: 0, losses: 0 },
    team: { played: 0, wins: 0, losses: 0 },
    private: { played: 0, wins: 0, losses: 0 },
    bots: { played: 0, wins: 0, losses: 0 }
  }
}

/**
 * Win rate in whole percent, or null for "no games yet" — a player with an
 * empty record has no rate, and 0/0 must never reach a division.
 */
export function winRate(r: CategoryRecord): number | null {
  return r.played === 0 ? null : Math.round((r.wins / r.played) * 100)
}

export const HistoryMessageSchema = z.object({
  t: z.literal('history'),
  seq,
  /**
   * One round trip feeds the whole profile screen: the recent-games list (capped
   * by the server) and the per-category record over the player's ENTIRE archive
   * — counting the capped list on the client would understate a veteran.
   */
  p: z.object({
    entries: z.array(HistoryEntrySchema),
    record: ModeRecordSchema,
    /**
     * The player's own achievements (author's list, 2026-07-27) — same round
     * trip, because the profile screen draws them next to the record table.
     * Optional: a reply built before the catalog existed is still a valid
     * reply, and the panel then simply has nothing to draw.
     */
    achievements: AchievementStateSchema.optional()
  })
})

// --- Players directory (author backlog #2) ---------------------------------------------
