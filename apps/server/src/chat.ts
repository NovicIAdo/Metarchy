// Persisted chat store (author backlog #3): the global room and player↔player
// DMs, their flags and their like/dislike reactions. Its own interface next to
// ProfileStore rather than another wing of GameStore — nothing here belongs to a
// game. Two backends behind it: MemoryChatStore below, SqlChatStore in
// chat-sql.ts, and test/chat.test.ts runs the same contract against both.
//
// Two invariants this file exists to hold:
//  1. The one-global-message-per-minute rule is derived from the PERSISTED
//     messages, never from a per-session timestamp — a reconnect or a server
//     restart must not hand anybody a fresh minute.
//  2. Counters are counted from the reaction/flag rows on every read. There is
//     no counter column, so there is nothing to drift.

import type {
  ChatAuthorView,
  ChatConversation,
  ChatCounts,
  ChatMessageEntry,
  ChatReaction,
  ChatSort
} from '@metarchy/protocol'
import { CHAT_FLAG_HIDE_THRESHOLD, CHAT_GLOBAL_COOLDOWN_MS } from '@metarchy/protocol'

/** The one room everybody shares. */
export const GLOBAL_ROOM = 'global'

/**
 * The conversation key of a private chat. Canonical (the two ids sorted), so
 * both directions land in ONE room whoever writes first. The server derives this
 * from the caller's own id plus the peer they named — a client never sends a
 * room, so it can never address a conversation it is not part of.
 */
export function dmRoomKey(a: string, b: string): string {
  return a < b ? `dm:${a}:${b}` : `dm:${b}:${a}`
}

/**
 * DM privacy, enforced on the server: only the two participants may read a
 * private room. Called for every message the client reaches for by id (a thread,
 * a reaction, a flag) — those ids could otherwise belong to somebody else's DM.
 */
export function canReadRoom(userId: string, room: string): boolean {
  if (room === GLOBAL_ROOM) return true
  const [, a, b] = room.split(':')
  return userId === a || userId === b
}

/** Enough of a message to authorize and to re-parent a reply. */
export interface ChatMessageRef {
  id: string
  room: string
  /** null = top-level; a reply to a reply attaches HERE, one level deep. */
  parentId: string | null
  /** Flagged away — no longer interactive. */
  hidden: boolean
}

export interface ChatPostInput {
  /** Generated by the caller (randomUUID), like every other id in this codebase. */
  id: string
  room: string
  authorId: string
  /** null in the global room; the addressee of a DM. */
  recipientId: string | null
  parentId: string | null
  body: string
  /**
   * Rolling window the author must have cleared in THIS room, in ms; 0 = no
   * limit. The check happens inside the same write, so it cannot be skipped.
   */
  cooldownMs: number
}

export type ChatPostResult =
  { ok: true; entry: ChatMessageEntry } | { ok: false; retryInMs: number }

export interface ChatPageQuery {
  room: string
  /** Whose `mine` / `myReaction` / `flaggedByMe` the rows carry. */
  viewerId: string
  sort: ChatSort
  limit: number
  offset: number
}

export interface ChatStore {
  /**
   * Teach the backend who a player is. The SQL backend has `profiles` and
   * ignores this; the memory backend has no profile table, so the hub introduces
   * each session on attach and that is where names and faces come from.
   */
  remember(author: ChatAuthorView): void

  /** Refused with `retryInMs` when the author is still inside their cooldown. */
  post(input: ChatPostInput): Promise<ChatPostResult>

  /**
   * One page of TOP-LEVEL messages under the chosen sort. Replies are counted,
   * not included — the client opens a thread separately.
   */
  listTopLevel(query: ChatPageQuery): Promise<{ rows: ChatMessageEntry[]; total: number }>

  /**
   * One thread. Always chronological, whatever the room's sort is: the sort
   * switch ranks the conversation, a thread is a conversation of its own and
   * reads top to bottom (the author asked for YouTube's comments).
   */
  listReplies(parentId: string, viewerId: string): Promise<ChatMessageEntry[]>

  /** For authorization and re-parenting; null when there is no such message. */
  loadRef(messageId: string): Promise<ChatMessageRef | null>

  /**
   * Like or dislike, one per (message, player): sending the reaction already
   * held clears it, the other one switches. null = no such message, or it was
   * flagged away.
   */
  react(messageId: string, userId: string, reaction: ChatReaction): Promise<ChatCounts | null>

  /**
   * Flag once per (message, player) — a repeat is a no-op, so ten flags from one
   * player are still one. At CHAT_FLAG_HIDE_THRESHOLD DISTINCT flaggers the
   * message is soft-removed. null = no such message, or already removed.
   */
  flag(messageId: string, userId: string): Promise<ChatCounts | null>

  /** My private conversations, most recent first — the DM picker. */
  listConversations(userId: string): Promise<ChatConversation[]>

  /** Resolve a peer by id (does this player exist?) or by exact nickname. */
  findPeer(by: { userId: string } | { nickname: string }): Promise<ChatAuthorView | null>

  /** ms until this player may post to the global room again; 0 = free now. */
  globalCooldownMs(userId: string): Promise<number>

  /** True when `userId` has closed the DM with `peerId` — their writes to me stop. */
  isBlocked(userId: string, peerId: string): Promise<boolean>
  /** Close (block=true) or reopen a private conversation; returns the new state. */
  setBlocked(userId: string, peerId: string, blocked: boolean): Promise<boolean>
  /** Does this user have any unread private message? Drives the shell dot. */
  hasUnreadDm(userId: string): Promise<boolean>
  /** Mark every DM of mine read up to now — opening the private tab clears the dot. */
  markAllDmRead(userId: string): Promise<void>
}

// --- Shared shaping ----------------------------------------------------------------

/**
 * A flagged-away message is served as a tombstone rather than dropped: the row
 * still anchors its thread, so the replies underneath stay readable and
 * addressable. Body and author are blanked — that is what "removed from the
 * chat" means here (see the migration for why a hard delete is worse).
 */
export function tombstone(entry: ChatMessageEntry): ChatMessageEntry {
  return { ...entry, author: null, body: '', mine: false, removed: true }
}

// --- Memory backend ----------------------------------------------------------------

interface MemMessage {
  id: string
  room: string
  authorId: string
  recipientId: string | null
  parentId: string | null
  body: string
  createdAt: number
  /** Insertion order. Date.now() has 1ms resolution, and two messages can land
   *  inside the same one — this is what keeps "newest" meaning "written last",
   *  the way the SQL backend's timestamps already do. */
  seq: number
  hiddenAt: number | null
}

export class MemoryChatStore implements ChatStore {
  private readonly messages: MemMessage[] = []
  private readonly byId = new Map<string, MemMessage>()
  /** message id → the players who flagged it (a set IS "different players"). */
  private readonly flags = new Map<string, Set<string>>()
  /** message id → player → their single reaction. */
  private readonly reactions = new Map<string, Map<string, ChatReaction>>()
  private readonly directory = new Map<string, ChatAuthorView>()
  private nextSeq = 1

  remember(author: ChatAuthorView): void {
    this.directory.set(author.userId, { ...author })
  }

  async post(input: ChatPostInput): Promise<ChatPostResult> {
    const now = Date.now()
    if (input.cooldownMs > 0) {
      const last = this.lastPostAt(input.authorId, input.room)
      if (last !== null && now - last < input.cooldownMs)
        return { ok: false, retryInMs: input.cooldownMs - (now - last) }
    }
    const row: MemMessage = {
      id: input.id,
      room: input.room,
      authorId: input.authorId,
      recipientId: input.recipientId,
      parentId: input.parentId,
      body: input.body,
      createdAt: now,
      seq: this.nextSeq++,
      hiddenAt: null
    }
    this.messages.push(row)
    this.byId.set(row.id, row)
    return { ok: true, entry: this.shape(row, input.authorId) }
  }

  async listTopLevel(query: ChatPageQuery): Promise<{ rows: ChatMessageEntry[]; total: number }> {
    const servable = this.messages.filter(
      (m) => m.room === query.room && m.parentId === null && this.isServable(m)
    )
    const sorted = [...servable].sort((a, b) => this.compare(a, b, query.sort))
    const page = sorted.slice(query.offset, query.offset + query.limit)
    return {
      rows: page.map((m) => this.shape(m, query.viewerId)),
      total: servable.length
    }
  }

  async listReplies(parentId: string, viewerId: string): Promise<ChatMessageEntry[]> {
    return this.messages
      .filter((m) => m.parentId === parentId && m.hiddenAt === null)
      .sort((a, b) => a.createdAt - b.createdAt || a.seq - b.seq)
      .map((m) => this.shape(m, viewerId))
  }

  async loadRef(messageId: string): Promise<ChatMessageRef | null> {
    const row = this.byId.get(messageId)
    if (!row) return null
    return { id: row.id, room: row.room, parentId: row.parentId, hidden: row.hiddenAt !== null }
  }

  async react(
    messageId: string,
    userId: string,
    reaction: ChatReaction
  ): Promise<ChatCounts | null> {
    const row = this.byId.get(messageId)
    if (!row || row.hiddenAt !== null) return null
    let mine = this.reactions.get(messageId)
    if (!mine) {
      mine = new Map()
      this.reactions.set(messageId, mine)
    }
    if (mine.get(userId) === reaction) mine.delete(userId)
    else mine.set(userId, reaction)
    return this.counts(row, userId)
  }

  async flag(messageId: string, userId: string): Promise<ChatCounts | null> {
    const row = this.byId.get(messageId)
    if (!row || row.hiddenAt !== null) return null
    let flaggers = this.flags.get(messageId)
    if (!flaggers) {
      flaggers = new Set()
      this.flags.set(messageId, flaggers)
    }
    flaggers.add(userId)
    if (flaggers.size >= CHAT_FLAG_HIDE_THRESHOLD) row.hiddenAt = Date.now()
    return this.counts(row, userId)
  }

  async listConversations(userId: string): Promise<ChatConversation[]> {
    const latest = new Map<string, MemMessage>()
    for (const m of this.messages) {
      if (m.recipientId === null) continue
      if (m.authorId !== userId && m.recipientId !== userId) continue
      const known = latest.get(m.room)
      if (!known || m.seq > known.seq) latest.set(m.room, m)
    }
    const items: ChatConversation[] = []
    for (const m of [...latest.values()].sort((a, b) => b.seq - a.seq)) {
      const peerId = m.authorId === userId ? (m.recipientId as string) : m.authorId
      const peer = this.directory.get(peerId)
      if (!peer) continue
      items.push({
        peer,
        lastBody: m.hiddenAt === null ? m.body : '',
        lastAt: new Date(m.createdAt).toISOString(),
        lastMine: m.authorId === userId
      })
    }
    return items
  }

  async findPeer(by: { userId: string } | { nickname: string }): Promise<ChatAuthorView | null> {
    if ('userId' in by) return this.directory.get(by.userId) ?? null
    const wanted = by.nickname.toLowerCase()
    for (const p of this.directory.values())
      if (p.nickname.toLowerCase() === wanted) return { ...p }
    return null
  }

  async globalCooldownMs(userId: string): Promise<number> {
    const last = this.lastPostAt(userId, GLOBAL_ROOM)
    if (last === null) return 0
    return Math.max(0, CHAT_GLOBAL_COOLDOWN_MS - (Date.now() - last))
  }

  private readonly blocks = new Map<string, Set<string>>()
  private readonly readCursors = new Map<string, Map<string, number>>()

  async isBlocked(userId: string, peerId: string): Promise<boolean> {
    return this.blocks.get(userId)?.has(peerId) ?? false
  }

  async setBlocked(userId: string, peerId: string, blocked: boolean): Promise<boolean> {
    let mine = this.blocks.get(userId)
    if (!mine) {
      mine = new Set()
      this.blocks.set(userId, mine)
    }
    if (blocked) mine.add(peerId)
    else mine.delete(peerId)
    return blocked
  }

  async hasUnreadDm(userId: string): Promise<boolean> {
    const cursors = this.readCursors.get(userId)
    let latestIncoming = 0
    for (const m of this.messages) {
      if (m.recipientId !== userId || m.hiddenAt !== null) continue
      if (m.createdAt > latestIncoming) latestIncoming = m.createdAt
    }
    if (latestIncoming === 0) return false
    let latestRead = 0
    for (const t of cursors?.values() ?? []) if (t > latestRead) latestRead = t
    return latestIncoming > latestRead
  }

  async markAllDmRead(userId: string): Promise<void> {
    const rooms = new Set<string>()
    for (const m of this.messages) if (m.recipientId === userId) rooms.add(m.room)
    let cursors = this.readCursors.get(userId)
    if (!cursors) {
      cursors = new Map()
      this.readCursors.set(userId, cursors)
    }
    const now = Date.now()
    for (const room of rooms) cursors.set(room, now)
  }

  private lastPostAt(userId: string, room: string): number | null {
    let last: number | null = null
    for (const m of this.messages)
      if (m.authorId === userId && m.room === room && (last === null || m.createdAt > last))
        last = m.createdAt
    return last
  }

  /**
   * Which top-level messages a room page serves: everything not flagged away,
   * plus a flagged-away message that still anchors a visible reply — dropping
   * that one would strand its whole thread. Both the page and `total` filter by
   * this, in both backends (chat-sql.ts SERVABLE), so the two cannot disagree.
   */
  private isServable(m: MemMessage): boolean {
    if (m.hiddenAt === null) return true
    return this.messages.some((r) => r.parentId === m.id && r.hiddenAt === null)
  }

  private compare(a: MemMessage, b: MemMessage, sort: ChatSort): number {
    if (sort === 'likes' || sort === 'dislikes') {
      const key = sort === 'likes' ? 'like' : 'dislike'
      const delta = this.countReaction(b.id, key) - this.countReaction(a.id, key)
      if (delta !== 0) return delta
    }
    // Newest at the BOTTOM: the stream reads top-to-bottom like a chat.
    return a.createdAt - b.createdAt || a.seq - b.seq
  }

  private countReaction(messageId: string, reaction: ChatReaction): number {
    let n = 0
    for (const r of this.reactions.get(messageId)?.values() ?? []) if (r === reaction) n += 1
    return n
  }

  private counts(row: MemMessage, viewerId: string): ChatCounts {
    return {
      messageId: row.id,
      likes: this.countReaction(row.id, 'like'),
      dislikes: this.countReaction(row.id, 'dislike'),
      myReaction: this.reactions.get(row.id)?.get(viewerId) ?? null,
      flags: this.flags.get(row.id)?.size ?? 0,
      flaggedByMe: this.flags.get(row.id)?.has(viewerId) ?? false,
      removed: row.hiddenAt !== null
    }
  }

  private shape(row: MemMessage, viewerId: string): ChatMessageEntry {
    const c = this.counts(row, viewerId)
    const entry: ChatMessageEntry = {
      id: row.id,
      parentId: row.parentId,
      author: this.directory.get(row.authorId) ?? {
        userId: row.authorId,
        nickname: row.authorId.slice(0, 8),
        avatar: null
      },
      body: row.body,
      createdAt: new Date(row.createdAt).toISOString(),
      likes: c.likes,
      dislikes: c.dislikes,
      myReaction: c.myReaction,
      flags: c.flags,
      flaggedByMe: c.flaggedByMe,
      replyCount:
        row.parentId === null
          ? this.messages.filter((r) => r.parentId === row.id && r.hiddenAt === null).length
          : 0,
      mine: row.authorId === viewerId,
      removed: false
    }
    return row.hiddenAt === null ? entry : tombstone(entry)
  }
}
