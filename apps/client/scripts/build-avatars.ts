// Extra avatar faces beyond the three launch ones: the four actor heads, reused
// from the committed theme art. The RSP coins used to be faces here too, but the
// default coins are game art every player owns — they belong to the free
// argument set, not the shop (see build-arg-skins.ts for the alloys that do
// sell). The blank coin stays as the GATO currency icon. Emits avatars/*.webp +
// a generated manifest (src/theme.avatars.gen.ts) merged into the cyberpunk theme.
// Ids must mirror protocol AVATAR_IDS; a client test keeps them in lockstep.
// Run: pnpm --filter @metarchy/client build:avatars

import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const CLIENT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const THEME = path.join(CLIENT_ROOT, 'public/themes/cyberpunk')
const COINS =
  process.env.AVATAR_COINS_SOURCE ??
  path.resolve(CLIENT_ROOT, '../../plan/visual-ref/Metarchy-assets/RSP-token')
const URL_ROOT = '/themes/cyberpunk/avatars'

/** id → source file (theme-relative or absolute). */
const AVATARS: Record<string, string> = {
  politician: path.join(THEME, 'actors/politician_head.webp'),
  robot: path.join(THEME, 'actors/robot_head.webp'),
  artist: path.join(THEME, 'actors/artist_head.webp'),
  scientist: path.join(THEME, 'actors/scientist_head.webp')
}

async function main() {
  const manifest: Record<string, string> = {}
  for (const [id, src] of Object.entries(AVATARS)) {
    const out = path.join(THEME, 'avatars', `${id}.webp`)
    const info = await sharp(src)
      .resize({ width: 256, height: 256 })
      .webp({ quality: 85 })
      .toFile(out)
    manifest[`avatar.${id}`] = `${URL_ROOT}/${id}.webp`
    console.log(`avatar.${id}`.padEnd(20), `${(info.size / 1024).toFixed(0).padStart(3)}K`)
  }
  // The GATO currency icon: the author's blank coin (the RSP "Пустышка").
  await sharp(path.join(COINS, 'Пустышка.png'))
    .resize({ width: 128, height: 128 })
    .webp({ quality: 85 })
    .toFile(path.join(THEME, 'avatars', 'gato.webp'))
  manifest['currency.gato'] = `${URL_ROOT}/gato.webp`
  const entries = Object.keys(manifest)
    .sort()
    .map((k) => `  '${k}': '${manifest[k]}'`)
    .join(',\n')
  const gen = `// GENERATED by scripts/build-avatars.ts — do not edit by hand.\n// Regenerate: pnpm --filter @metarchy/client build:avatars\n\nexport const avatarAssets: Record<string, string> = {\n${entries}\n}\n`
  await writeFile(path.join(CLIENT_ROOT, 'src/theme.avatars.gen.ts'), gen)
}

await main()
