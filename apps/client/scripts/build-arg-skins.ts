// Argument-coin skins: recolours of the author's four RSP tokens (rock, paper,
// scissors, dummy) into buyable metal/digital sets. The canonical warm-gold
// coins stay free — these are the shop goods, so each set must read as a
// different alloy at badge size (48px) without touching the engraved symbol.
//
// Recipes are duotones: sharp's .tint() keeps luminance and swaps chroma, which
// preserves the sculpted highlights that make the coin look like metal. Source
// pack is gitignored — the webp outputs are committed.
// Ids must mirror protocol ARG_SKIN_IDS; a client test keeps them in lockstep.
// Run: pnpm --filter @metarchy/client build:arg-skins

import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const CLIENT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const THEME = path.join(CLIENT_ROOT, 'public/themes/cyberpunk')
const COINS =
  process.env.AVATAR_COINS_SOURCE ??
  path.resolve(CLIENT_ROOT, '../../plan/visual-ref/Metarchy-assets/RSP-token')
const URL_ROOT = '/themes/cyberpunk/arg-skins'
const SIZE = 160

/** Argument type → author's source file (the same four the free set is cut from). */
const SOURCES: Record<string, string> = {
  rock: 'Камень.png',
  paper: 'Бумага.png',
  scissors: 'Ножницы.png',
  dummy: 'Пустышка.png'
}

/** Horizontal phosphor lines, drawn only over the coin ('atop' keeps its alpha). */
const scanlines = (period: number, opacity: number) =>
  Buffer.from(
    `<svg width="${SIZE}" height="${SIZE}">${Array.from(
      { length: Math.floor(SIZE / period) },
      (_, i) =>
        `<rect x="0" y="${i * period}" width="${SIZE}" height="1" fill="#000" opacity="${opacity}"/>`
    ).join('')}</svg>`
  )

interface Recipe {
  /** Contrast/brightness pass before the duotone: [multiplier, offset]. */
  levels: [number, number]
  /** Duotone colour — the alloy. */
  tint: string
  scanlines?: { period: number; opacity: number }
}

const SETS: Record<string, Recipe> = {
  // Cool desaturated metal: the polished-platinum read.
  silver: { levels: [1.08, -10], tint: '#c2d2e6' },
  // Deep antique copper — darker and redder than the canonical pale gold, so
  // the two never get confused on the board.
  bronze: { levels: [1.0, -6], tint: '#8c5320' },
  // Phosphor green on crushed darks + faint scanlines: the terminal read.
  matrix: { levels: [1.2, -50], tint: '#00ff41', scanlines: { period: 4, opacity: 0.13 } }
}

async function main() {
  const manifest: Record<string, string> = {}
  for (const [set, recipe] of Object.entries(SETS)) {
    await mkdir(path.join(THEME, 'arg-skins', set), { recursive: true })
    for (const [arg, file] of Object.entries(SOURCES)) {
      const out = path.join(THEME, 'arg-skins', set, `${arg}.webp`)
      let img = sharp(path.join(COINS, file))
        .linear(recipe.levels[0], recipe.levels[1])
        .tint(recipe.tint)
        .resize(SIZE, SIZE)
      if (recipe.scanlines)
        img = img.composite([
          { input: scanlines(recipe.scanlines.period, recipe.scanlines.opacity), blend: 'atop' }
        ])
      const info = await img.webp({ quality: 85 }).toFile(out)
      manifest[`argSkin.${set}.${arg}`] = `${URL_ROOT}/${set}/${arg}.webp`
      console.log(
        `argSkin.${set}.${arg}`.padEnd(28),
        `${(info.size / 1024).toFixed(0).padStart(3)}K`
      )
    }
  }
  const entries = Object.keys(manifest)
    .sort()
    .map((k) => `  '${k}': '${manifest[k]}'`)
    .join(',\n')
  const gen = `// GENERATED by scripts/build-arg-skins.ts — do not edit by hand.\n// Regenerate: pnpm --filter @metarchy/client build:arg-skins\n\nexport const argSkinAssets: Record<string, string> = {\n${entries}\n}\n`
  await writeFile(path.join(CLIENT_ROOT, 'src/theme.argskins.gen.ts'), gen)
}

await main()
